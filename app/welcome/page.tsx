import type { Metadata } from "next";
import Link from "next/link";
import { redirect } from "next/navigation";
import { ArrowLeft, BadgeCheck, FileSignature } from "lucide-react";
import { OnboardingForm } from "@/components/onboarding-form";
import { getSessionUser, safeNext } from "@/lib/auth";
import { normalizeUsername } from "@/lib/profile";

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Set up your byline",
  robots: { index: false, follow: false },
};

export default async function WelcomePage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const params = await searchParams;
  const next = safeNext(typeof params.next === "string" ? params.next : "/", "/");
  const editing = params.edit === "1";
  const user = await getSessionUser();

  if (!user) {
    redirect(`/login?next=${encodeURIComponent(`/welcome?next=${encodeURIComponent(next)}`)}`);
  }

  if (user.onboardedAt && !editing) redirect(next);

  const fallbackUsername =
    normalizeUsername(user.username ?? user.email.split("@")[0] ?? "") ||
    `reader_${user.id.replace(/-/g, "").slice(0, 8)}`;

  return (
    <div className="mx-auto max-w-4xl px-4 py-8 sm:px-6 sm:py-12">
      <Link
        href={editing ? "/account" : "/"}
        className="inline-flex items-center gap-1.5 font-mono text-[9px] uppercase tracking-[0.14em] text-muted-foreground hover:text-foreground"
      >
        <ArrowLeft className="size-3" /> {editing ? "Back to account" : "Back to the wire"}
      </Link>

      <div className="mt-5 grid gap-6 border-b-2 border-foreground pb-6 sm:grid-cols-[1fr_auto] sm:items-end">
        <div>
          <p className="font-mono text-[9px] uppercase tracking-[0.2em] text-primary">
            {editing ? "Personnel file" : "One-time paperwork"}
          </p>
          <h1 className="display mt-2 text-[2.5rem] leading-[0.95] tracking-[-0.035em] sm:text-[3.4rem]">
            Put a face
            <br />
            to the byline.
          </h1>
          <p className="mt-4 max-w-lg text-[13.5px] leading-relaxed text-muted-foreground">
            Your comments carry this name and avatar across the wire. Pick something you would be happy to defend
            in a mains answer. It takes one visit, and the desk remembers it.
          </p>
        </div>
        <div className="flex items-center gap-2 border border-border bg-card px-3 py-2">
          <FileSignature className="size-4 text-primary" />
          <div>
            <p className="font-mono text-[8px] uppercase tracking-[0.14em] text-muted-foreground">File status</p>
            <p className="mt-0.5 flex items-center gap-1 text-[12px] font-medium">
              <BadgeCheck className="size-3.5 text-success" />
              {user.onboardedAt ? "On file" : "Awaiting signature"}
            </p>
          </div>
        </div>
      </div>

      {user.onboardSkippedAt && !user.onboardedAt ? (
        <p className="mt-4 border-l-2 border-warning bg-warning/10 px-3 py-2 text-[12px] leading-relaxed text-warning">
          You skipped this earlier. Your generated byline works, but the reminder stays here until you choose an
          avatar.
        </p>
      ) : null}

      <div className="mt-6 border border-border bg-card p-4 shadow-xs sm:p-6">
        <OnboardingForm
          name={user.name}
          username={fallbackUsername}
          avatar={user.avatar}
          userId={user.id}
          next={next}
        />
      </div>

      <p className="mt-5 font-mono text-[8.5px] uppercase leading-relaxed tracking-[0.1em] text-muted-foreground">
        Public byline · no email or phone is ever shown · username can be changed later from account settings
      </p>
    </div>
  );
}
